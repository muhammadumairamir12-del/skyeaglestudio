window.renderJourneyCaseStudies = function (containerId) {
  const container = document.getElementById(containerId);
  if (!container || !Array.isArray(window.journeyCaseStudies)) return;

  container.classList.add('project-split-list');
  container.innerHTML = '';

  window.journeyCaseStudies.forEach((study, index) => {
    const linked = (window.projectsData || []).find((p) =>
      p.slug === study.projectSlug || p.slug === study.id
    );
    // Prefer Journey image paths so screenshots always resolve correctly on /journey
    const imageUrls = (study.imageUrls && study.imageUrls.length)
      ? study.imageUrls.slice()
      : ((linked && linked.imageUrls) || []);
    const project = Object.assign({}, linked || {}, {
      name: study.clientName,
      clientName: study.clientName,
      industry: study.industry,
      type: study.year ? study.year + ' · Client work' : 'Client work',
      problem: study.problem,
      solution: study.solution,
      outcome: study.outcome,
      price: '',
      priceWhy: '',
      techStack: study.techStack,
      technologies: study.techStack,
      liveUrl: study.liveUrl || (linked && linked.liveUrl) || '',
      slug: (linked && linked.slug) || study.projectSlug || '',
      projectSlug: (linked && linked.slug) || study.projectSlug || '',
      imageUrl: study.imageUrl || (linked && linked.imageUrl) || '',
      imageUrl2: study.imageUrl2 || (linked && linked.imageUrl2) || '',
      imageUrls: imageUrls
    });

    if (study.placeholder) {
      const card = document.createElement('article');
      card.className = 'journey-client-card is-placeholder';
      card.innerHTML = '<div class="journey-card-index">' + String(index + 1).padStart(2, '0') + '</div>' +
        '<div class="journey-card-head"><div><h3>' + study.clientName + '</h3><p class="journey-card-industry">' + (study.industry || '') + '</p></div></div>' +
        '<span class="journey-status-badge">Case study coming soon</span>';
      container.appendChild(card);
      return;
    }

    if (typeof window.createProjectSplitBlock === 'function') {
      const block = window.createProjectSplitBlock(project, index, { mode: 'journey' });
      container.appendChild(block);
    }
  });
};
